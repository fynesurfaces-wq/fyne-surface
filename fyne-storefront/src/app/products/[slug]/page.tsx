// ── ISR: pre-render every active product at build, refresh every 5 minutes ──
export const revalidate = REVALIDATE;
export const dynamicParams = true; // new products render on first request, then get cached

export async function generateStaticParams() {
  const slugs: { slug: string }[] = [];
  let page = 1;
  // Walk all pages (API caps at 60 per page). Returns [] if the API is offline at build time.
  for (;;) {
    const res = await getProducts({ page, limit: 60 });
    slugs.push(...res.data.map((p) => ({ slug: p.slug })));
    if (!res.pagination.hasNextPage) break;
    page += 1;
  }
  return slugs;
}

type Props = { params: { slug: string } };

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const p = await getProduct(params.slug);
  if (!p) return { title: 'Product not found', robots: { index: false } };

  const images = p.images.length
    ? p.images.slice(0, 4).map((i) => ({ url: i.url, alt: i.alt || p.name, width: 1200, height: 1500 }))
    : undefined;

  return {
    title: { absolute: p.seo.title },
    description: p.seo.description,
    keywords: p.seo.keywords.length ? p.seo.keywords : undefined,
    alternates: { canonical: toPath(p.seo.canonicalUrl) },
    openGraph: {
      type: 'website',
      title: p.seo.title,
      description: p.seo.description,
      url: toPath(p.seo.canonicalUrl),
      siteName: p.brand,
      images,
    },
    twitter: { card: images ? 'summary_large_image' : 'summary', title: p.seo.title, description: p.seo.description, images: images?.map((i) => i.url) },
    other: {
      // Open Graph product price tags (Pinterest/Facebook rich pins)
      'product:price:amount': String(p.price.amount),
      'product:price:currency': 'INR',
      'product:availability': p.availability.inStock ? 'in stock' : 'out of stock',
      'product:retailer_item_id': p.sku,
    },
  };
}

