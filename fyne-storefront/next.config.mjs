/** @type {import('next').NextConfig} */

// Express API origin (server-side). The browser only ever talks to this
// storefront's own origin; Next proxies API + SEO files to the backend.
const API_ORIGIN = process.env.API_ORIGIN || 'http://localhost:5000';

const nextConfig = {
  reactStrictMode: true,
  poweredByHeader: false,
  images: {
    // WebP keeps transfer sizes low without the noticeably slower AVIF encoding
    // and decode cost on modest storefront servers and phones.
    formats: ['image/webp'],
    remotePatterns: [
      { protocol: 'https', hostname: 'ik.imagekit.io' }, // product photos (admin uploads)
      { protocol: 'https', hostname: 'res.cloudinary.com' }, // legacy product photos
      { protocol: 'https', hostname: 'placehold.co' }, // simulated uploads in dev
    ],
  },
  async rewrites() {
    return [
      { source: '/api/v1/:path*', destination: `${API_ORIGIN}/api/v1/:path*` },
      // Dynamic SEO/GEO files generated by the backend, served on the storefront domain
      { source: '/sitemap.xml', destination: `${API_ORIGIN}/sitemap.xml` },
      { source: '/robots.txt', destination: `${API_ORIGIN}/robots.txt` },
      { source: '/llms.txt', destination: `${API_ORIGIN}/llms.txt` },
    ];
  },
  async headers() {
    return [
      {
        source: '/:path*',
        headers: [
          { key: 'X-Content-Type-Options', value: 'nosniff' },
          { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
          { key: 'X-Frame-Options', value: 'SAMEORIGIN' },
        ],
      },
    ];
  },
};

export default nextConfig;
